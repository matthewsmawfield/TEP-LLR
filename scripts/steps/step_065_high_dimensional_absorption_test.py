"""
Step 065: High-Dimensional Ephemeris-Like Basis Absorption Test
===============================================================

Directly addresses the peer-review criticism that the toy orbital model
(Step 054, {1, cos M, sin M}) underestimates the degrees of freedom available
to modern planetary ephemerides (INPOP, DE430) to absorb synodic variance.

The reviewer claims: "INPOP and DE430 are not simple toy Keplerian solvers.
They are fully relativistic, N-body numerical integrations fitting well over
100 parameters... What you are measuring in the residuals is only the 'leaked',
unabsorbed fraction."

This step rigorously tests absorption with a realistic 80+ parameter ephemeris-
like basis and, crucially, moves beyond the simple central-frequency argument
to the sideband structure that is the dynamical signature of the TEP effect.

Three experiments are performed:

A.  Static cos(D) injection on white noise.
    Measures how much a simple synodic signal is absorbed by the basis.
    This is a worst-case linear scenario; honest reporting is required.

B.  Dynamically modulated TEP signal injection.
    Injects cos(D) × heliocentric_modulation, which generates sidebands at
    D ± annual frequencies.  A basis without explicit product terms cannot
    absorb these cross-frequency components, even if it can partially absorb
    the central cos(D) carrier.

C.  Sideband survival on REAL INPOP19a residuals.
    Fits the high-DOF basis to the actual INPOP residuals and checks
    whether spectral sideband power at D ± l' survives.  The sidebands are
    the smoking gun: they are produced only by a dynamically varying η(t) and
    cannot be generated by static ephemeris parameter adjustments.

Key physical insight: while a large linear basis may partially absorb a pure
synodic carrier on a non-uniform sampling manifold (via correlations with
station trends and annual cycles), sideband survival is the critical diagnostic.
This step is a high-dimensional linear stress test. It is not a symplectic
N-body numerical integrator and cannot emulate the iterative dynamic planetary
potentials handled by the actual Fortran/C++ code underlying INPOP or DE430.
While the proxy strongly suggests sideband survival, only a source-level
numerical refit with a dynamic eta parameter inside IMCCE or JPL integrators
can definitively close the absorption loop.
"""

